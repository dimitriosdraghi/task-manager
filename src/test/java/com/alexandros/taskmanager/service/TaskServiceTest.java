package com.alexandros.taskmanager.service;

import com.alexandros.taskmanager.entity.Role;
import com.alexandros.taskmanager.entity.Task;
import com.alexandros.taskmanager.entity.User;
import com.alexandros.taskmanager.exception.TaskNotFoundException;
import com.alexandros.taskmanager.repository.TaskRepository;
import com.alexandros.taskmanager.repository.UserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/** Unit tests for the ownership rules, with mocked repositories (no database). */
@ExtendWith(MockitoExtension.class)
class TaskServiceTest {

    @Mock
    private TaskRepository taskRepository;

    @Mock
    private UserRepository userRepository;

    @InjectMocks
    private TaskService taskService;

    private User alex;   // USER, id 1
    private User maria;  // ADMIN, id 2
    private Task mariasTask;

    @BeforeEach
    void setUp() {
        // ids are normally generated by the database
        alex = new User("alex", "hash", Role.USER);
        ReflectionTestUtils.setField(alex, "id", 1L);
        maria = new User("maria", "hash", Role.ADMIN);
        ReflectionTestUtils.setField(maria, "id", 2L);
        mariasTask = new Task("Gym", null, maria);
        ReflectionTestUtils.setField(mariasTask, "id", 3L);
    }

    @Test
    void userCannotDeleteSomeoneElsesTask() {
        when(userRepository.findByUsername("alex")).thenReturn(Optional.of(alex));
        when(taskRepository.findById(3L)).thenReturn(Optional.of(mariasTask));

        assertThatThrownBy(() -> taskService.deleteTask(3L, "alex"))
                .isInstanceOf(AccessDeniedException.class);    // → 403

        verify(taskRepository, never()).delete(any());
    }

    @Test
    void adminCanDeleteSomeoneElsesTask() {
        Task alexTask = new Task("Groceries", null, alex);
        ReflectionTestUtils.setField(alexTask, "id", 1L);
        when(userRepository.findByUsername("maria")).thenReturn(Optional.of(maria));
        when(taskRepository.findById(1L)).thenReturn(Optional.of(alexTask));

        taskService.deleteTask(1L, "maria");

        verify(taskRepository).delete(alexTask);
    }

    @Test
    void ownerCanSeeOwnTask() {
        when(userRepository.findByUsername("maria")).thenReturn(Optional.of(maria));
        when(taskRepository.findById(3L)).thenReturn(Optional.of(mariasTask));

        var response = taskService.getTask(3L, "maria");

        assertThat(response.title()).isEqualTo("Gym");
        assertThat(response.owner()).isEqualTo("maria");
    }

    @Test
    void missingTaskGivesNotFound() {
        when(userRepository.findByUsername("alex")).thenReturn(Optional.of(alex));
        when(taskRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> taskService.getTask(99L, "alex"))
                .isInstanceOf(TaskNotFoundException.class);
    }
}
